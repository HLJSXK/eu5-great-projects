"""Generate GP-owned CMF GUI variable suppressions from explicit local data."""
from pathlib import Path
import yaml
REPO_ROOT = Path(__file__).resolve().parents[4]
HEADER = "# @Generated by scripts/in_game/common/on_action/gen_tv_cmf_suppressions.py\n# Data: data/cmf_warning_suppressions.yaml\n"
def generate(targets: list[str], callback: str = "tv_cmf_warning_suppressions_monthly_pulse") -> str:
    lines = [
        HEADER.rstrip(),
        "",
        f"{callback} = {{",
        "\teffect = {",
        "\t\tif = {",
        "\t\t\tlimit = { always = no }",
    ]
    for target in targets:
        lines.append(f"\t\t\tcmf_suppress = {{ v = {target} }}")
    lines.extend(
        [
            "\t\t}",
            "\t}",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main():
    data = yaml.safe_load((REPO_ROOT / "data/cmf_warning_suppressions.yaml").read_text(encoding="utf-8"))
    targets = sorted(set(data["extra_suppressions"]))
    output = REPO_ROOT / "src/in_game/common/on_action/tv_engineering_department_cmf_suppressions.txt"
    output.write_text(generate(targets, "tv_engineering_department_cmf_warning_suppressions_monthly_pulse"), encoding="utf-8-sig", newline="\n")
if __name__ == "__main__":
    main()
