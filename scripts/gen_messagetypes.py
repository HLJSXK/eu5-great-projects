"""Generate GP's additive message types from its own notification policy."""
from pathlib import Path
import re
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src/main_menu/gui/messagetypes/tv_engineering_department_messagetypes.txt"
def action_ids_under(*dirs):
    actions = set()
    for directory in dirs:
        for path in directory.glob("*.txt"):
            actions.update(re.findall(r"(?m)^([a-z][A-Za-z0-9_]*)\s*=\s*\{", path.read_text(encoding="utf-8-sig")))
    return actions
def message_action_id(name):
    for prefix, suffix in (("PERFORM_", "_ACTION"), ("WE_PERFORM_", "_ACTION"), ("ACTION_", "_PERFORMED_ON_US_TARGET"), ("ACTION_", "_PERFORMED_ON_US")):
        if name.startswith(prefix) and name.endswith(suffix):
            return name[len(prefix):-len(suffix)]
    return None
def outputs():
    policy = (ROOT / "data/message_types.txt").read_text(encoding="utf-8-sig")
    actions = set()
    for kind in ("generic_actions", "country_interactions"):
        for path in (ROOT / "src/in_game/common" / kind).glob("*.txt"):
            actions.update(re.findall(r"(?m)^([a-z][A-Za-z0-9_]*)\s*=\s*\{", path.read_text(encoding="utf-8-sig")))
    missing = [a for a in sorted(actions) if not re.search(r"(?m)^PERFORM_" + re.escape(a) + r"_ACTION\s*=", policy)]
    if missing:
        raise ValueError(f"Add notification policies to data/message_types.txt: {missing}")
    return {OUT: "# @Generated by scripts/gen_messagetypes.py\n# Data: data/message_types.txt\n\n" + policy}
def main():
    for path, content in outputs().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8-sig", newline="\n")
if __name__ == "__main__":
    main()
