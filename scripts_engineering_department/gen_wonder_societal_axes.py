"""Extract the ritual direction catalog from the checked-in vanilla definitions."""
from pathlib import Path

from vanilla_takeover.parse import parse
from wonder_mechanics.io import dump_yaml_document

ROOT = Path(__file__).resolve().parents[1]
SOURCE = '.eu5-base/reference_game_files/game/in_game/common/societal_values/00_default.txt'
SCRIPT = 'scripts_engineering_department/gen_wonder_societal_axes.py'


def generate():
    text = (ROOT / SOURCE).read_text(encoding='utf-8-sig')
    axes = {}
    for node in parse(text):
        if not node.children:
            continue
        left, right = node.key.split('_vs_')
        allow = node.child('allow')
        axes[node.key] = {
            'left': left, 'right': right, 'age': node.scalar('age') or None,
            'conditional': allow is not None,
            'allow_script': text[allow.opening + 1:allow.closing].strip() if allow else '',
            'left_sign': -1, 'right_sign': 1,
            'monthly_left': f'monthly_towards_{left}', 'monthly_right': f'monthly_towards_{right}',
            'left_icon': f'gfx/interface/icons/societal_values/{node.key}_left.dds',
            'right_icon': f'gfx/interface/icons/societal_values/{node.key}_right.dds',
        }
    if len(axes) != 17:
        raise ValueError(f'Expected 17 vanilla axes, got {len(axes)}; review the catalog before updating.')
    return f'# @Generated by {SCRIPT}\n# Data: {SOURCE}\n# Do not edit directly.\n' + dump_yaml_document({'societal_axes': axes})


if __name__ == '__main__':
    output = ROOT / 'data/wonder_societal_axes.yaml'
    output.write_text(generate(), encoding='utf-8-sig', newline="\n")
    print(f'Wrote {output.relative_to(ROOT)}')
