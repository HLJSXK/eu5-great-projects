"""Render new ED takeover helpers. Vanilla copies are handled by rewrite.py."""


from .parse import ROOT
from .scan import scan_reference


def name(wonder, suffix):
    return f"tv_vw_{wonder['key']}_{suffix}"


def final_type(wonder):
    return next(iter([wonder["final_building"]]))


def block(key, body):
    return key + " = {\n" + "\n".join("\t" + line if line else "" for line in body.splitlines()) + "\n}"


def output(script, relative, contents):
    path = ROOT / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    header = f"# @Generated by {script}\n# Sources: data/unique_wonders.yaml + .eu5-base/reference_game_files/game\n# Do not edit; regenerate from declared carriers.\n\n"
    path.write_text(header + contents.rstrip() + "\n", encoding="utf-8-sig", newline="\n")
    print(f"Wrote {relative}")


def read_requirements(scan):
    result = {}
    for site in scan.sites:
        scope = {"has": "here", "level": "here", "max": "here", "art_here": "here", "owned": "owned", "art_owned": "owned", "anywhere": "anywhere"}.get(site.form)
        if scope:
            result.setdefault(site.carrier.wonder["key"], set()).add(scope)
    return result


def triggers():
    scan = scan_reference()
    requirements = read_requirements(scan)
    wonders = {c.wonder["key"]: c.wonder for c in scan.carriers.values()}
    chunks = []
    for key, w in wonders.items():
        site, final = w["location"], final_type(w)
        chunks.append(block(name(w, "gate_trigger"), f"location:{site}.owner ?= root"))
        local = []
        for c in scan.carriers.values():
            if c.wonder["key"] != key:
                continue
            if c.kind == "art":
                local.append(f"any_work_of_art_in_location = {{ this ?= work_of_art:{c.key} }}")
            elif c.kind == "building":
                local.append(f"location_building_level = {{ building_type = building_type:{c.key} value >= $vanilla_level$ }}")
        local_presence = local[0] if len(local) == 1 else block("OR", "\n".join(local))
        level = f"location_building_level = {{ building_type = building_type:{final} value >= $ed_level$ }}"
        for scope in sorted(requirements.get(key, [])):
            if scope == "here":
                body = block("AND", f"this = location:{site}\n{level}") + "\n" + local_presence
            elif scope == "owned":
                body = block("AND", f"owns = location:{site}\nlocation:{site} = {{ {level} }}") + "\n" + block("any_owned_location", local_presence)
            else:
                arts = [c.key for c in scan.carriers.values() if c.wonder["key"] == key and c.kind == "art"]
                assert arts
                body = f"location:{site} = {{ {level} }}\n" + "\n".join(f"exists = work_of_art:{a}" for a in arts)
            chunks.append(block(name(w, f"present_{scope}_trigger"), block("OR", body)))
    return "\n\n".join(chunks)


def operations():
    scan = scan_reference()
    chunks = []
    used = {(s.carrier.wonder["key"], s.op) for s in scan.sites if s.form == "write"}
    wonders = {c.wonder["key"]: c.wonder for c in scan.carriers.values()}
    for key, op in sorted(used):
        w = wonders[key]
        if op in {"raise", "lower"}:
            body = f"tv_wonder_{op}_unique_level_effect = {{ wonder = {key} }}"
        else:
            debt = name(w, "damage_debt")
            if op == "damage":
                change = block("if", f"limit = {{ has_variable = {debt} }}\nchange_variable = {{ name = {debt} add = 1 }}") + "\n" + block("else", f"set_variable = {{ name = {debt} value = 1 }}")
                body = block(f"location:{w['location']}", block("if", f"limit = {{ location_building_level = {{ building_type = building_type:{final_type(w)} value >= 2 }} }}\ntv_wonder_lower_unique_level_effect = {{ wonder = {key} }}\n{change}"))
            elif op == "restore":
                change = block("if", f"limit = {{ var:{debt} = 1 }}\nremove_variable = {debt}") + "\n" + block("else", f"change_variable = {{ name = {debt} subtract = 1 }}")
                body = block(f"location:{w['location']}", block("if", f"limit = {{ has_variable = {debt} }}\n" + block("if", f"limit = {{ var:{debt} > 0 }}\ntv_wonder_raise_unique_level_effect = {{ wonder = {key} }}\n{change}")))
            else:
                raise ValueError(op)
        chunks.append(block(name(w, f"{op}_effect"), body))
    return "\n\n".join(chunks)


def startup_reconcile():
    chunks = []
    for s in scan_reference().sites:
        if s.form != "startup":
            continue
        c, ed_site = s.carrier, s.carrier.wonder["location"]
        if c.kind == "art":
            # Artwork placement is read from the live art object, independently
            # of both the setup declaration and the fixed ED site.
            check = f"exists = work_of_art:{c.key}\nwork_of_art:{c.key} ?= {{ location.owner ?= location:{ed_site}.owner }}"
            chunks.append(block("if", block("limit", check) + f"\ndestroy_art = work_of_art:{c.key}"))
        else:
            # Vanilla common/generic_actions/catholic.txt uses this exact forced
            # removal target syntax; effects.log declares location -> building.
            # s.location is the setup instance site; ed_site is the ED site.
            # Equal sites in the current bookmarks intentionally reduce this
            # comparison to an ownership-existence check.
            instance_site = s.location
            check = f"owner ?= location:{ed_site}.owner"
            removal = f'destroy_building_forcefully = "building(building_type:{c.key}|owner)"'
            chunks.append(block(f"location:{instance_site}", block("if", f"limit = {{ {check} }}\n{removal}")))
        s.status = "开局对齐"
    return block("tv_vw_startup_reconcile_effect", "\n".join(chunks))


def buildings():
    from .parse import splice
    chunks = []
    for c in scan_reference().carriers.values():
        if c.kind != "building":
            continue
        source, node = c.definition
        allow = [n for n in node.children if n.key == "allow"]
        if len(allow) > 1:
            raise ValueError(f"Multiple vanilla allow blocks: {c.key}")
        condition = block("custom_tooltip", f"text = TV_VW_CARRIER_LOCKED_TT\nNOT = {{ owner ?= location:{c.wonder['location']}.owner }}")
        target = allow[0] if allow else node
        addition = "\n".join("\t\t" + line for line in condition.splitlines()) + "\n" if allow else "\t" + block("allow", condition).replace("\n", "\n\t") + "\n"
        position = source.text.rfind("\n", 0, target.closing) + 1
        if source.text[position:target.closing].strip():
            position = target.closing
            addition = "\n" + addition + ("\t" if allow else "")
        raw = source.raw(node)
        edits = [(position-node.start, position-node.start, addition)]
        # REPLACE replaces the building, but its inline production methods still
        # register globally alongside vanilla's originals. Give the copies their
        # own ids while keeping every production-method field unchanged.
        for group in node.children:
            if group.key == "unique_production_methods":
                for method in group.children:
                    start = method.start - node.start
                    edits.append((start, start + len(method.key), "tv_vw_" + method.key))
        chunks.append("REPLACE:" + splice(raw, edits))
    return "\n\n".join(chunks)


DAMAGE_EFFECTS = (
    "minor_destroy_building_levels_in_location",
    "major_destroy_building_levels_in_location",
    "catastrophic_destroy_building_levels_in_location",
)


def final_dispatch():
    from wonder_mechanics.io import load_all_wonder_mechanics
    from wonder_mechanics.rituals import ritual_style_ids
    wonders, _ = load_all_wonder_mechanics()
    dispatch = {}
    for w in wonders:
        final = w["final_building"]
        if final in dispatch:
            raise ValueError(f"Duplicate ED final building: {final}")
        dispatch[final] = w
    return dispatch


def damage():
    from .parse import REFERENCE, Source
    source = Source.read(REFERENCE / "in_game/common/scripted_effects/location_effects.txt")
    definitions = {n.key: n for n in source.definitions}
    branches = []
    for final, w in final_dispatch().items():
        test = f"prev = {{ building_type = building_type:{final} building_level >= 2 }}"
        kind = "unique" if w.get("is_unique") else "generic"
        call = f"tv_wonder_lower_{kind}_level_effect = {{ wonder = {w['key']} }}"
        branches.append(block("if" if not branches else "else_if", f"limit = {{ {test} }}\n{call}"))
    guard = "is_key_in_global_variable_map = { name = tv_wonder_final_building_type_to_wonder_id target = prev.building_type }"
    ed = block("if", f"limit = {{ {guard} }}\n" + "\n".join(branches))
    chunks = []
    for key in DAMAGE_EFFECTS:
        n = definitions[key]
        inner = source.text[n.opening+1:n.closing]
        # Preserve the complete vanilla body byte-for-byte in the fallback arm.
        chunks.append(f"REPLACE:{key} = {{\n" + "\n".join("\t" + line for line in ed.splitlines()) + "\n\telse = {" + inner + "}\n}")
    return "\n\n".join(chunks)
