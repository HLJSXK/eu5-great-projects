"""Generate a country sale effect backed by timed negative goods demand.

Public API (country scope)::

    tv_sell_goods_with_temporary_supply_effect = {
        market = capital.market
        goods = goods:medicaments
        amount = 15
        time = 6
    }

market/goods accept scope links; amount/time accept scalar script values evaluated
in the calling country. Gold is paid once, amount * current target-market price * time,
before applying -amount demand for time months. There are no recurring payments.
This offsets demand; it does not create stockpile goods or real production.
Missing targets, unsupported goods, and nonpositive amount/time do nothing.
Repeated applications use the engine's add_temporary_demand lifecycle.
The visible description preserves vanilla sell_goods_to_market wording in all
six perspectives/tenses, adapting its native-only tokens to scripted bindings.

Evidence in .eu5-base/reference_game_files/game:
  in_game/common/goods_demand/from_events.txt: lutheran_dont_eat_fish (fish = -1)
  in_game/events/economy/prices.txt: prices.4 (timed negative demand)
  in_game/events/debug/000_johan_debug.txt: add_temporary_demand scale/months
  in_game/common/country_interactions/gra_trade_prestige_silk.txt: price_in_market
Official effects.log: save_scope_value_as, add_gold, add_temporary_demand.

Static demand IDs are generated for vanilla and this mod's goods. Regenerate when
adding goods. No runtime country/market variable stores or monthly pulses are used.
"""

from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
GENERATOR = "scripts_engineering_department/gen_market_supply_effects.py"
HEADER = f"# @Generated by {GENERATOR}\n# Edit the generator and goods inputs; do not hand-edit.\n\n"
EFFECT_PATH = "src/in_game/common/scripted_effects/tv_market_supply_effects.txt"
DEMAND_PATH = "src/in_game/common/goods_demand/tv_market_supply.txt"
EFFECT_LOC_PATH = "src/in_game/common/effect_localization/tv_market_supply_effects.txt"
VALUES_PATH = "src/in_game/common/script_values/tv_market_supply_values.txt"
PAYOUT_VALUE = "tv_market_supply_payout_value"
DESCRIPTION = "tv_sell_goods_with_temporary_supply_description"
SALE_LOCALIZATIONS = {
    "global": "SELL_GOODS_TO_MARKET_EFFECT",
    "first": "FIRST_SELL_GOODS_TO_MARKET_EFFECT",
    "third": "THIRD_SELL_GOODS_TO_MARKET_EFFECT",
    "global_past": "PAST_SELL_GOODS_TO_MARKET_EFFECT",
    "first_past": "PAST_FIRST_SELL_GOODS_TO_MARKET_EFFECT",
    "third_past": "PAST_THIRD_SELL_GOODS_TO_MARKET_EFFECT",
}


def goods_ids():
    goods = set()
    for folder in (
        ROOT / ".eu5-base/reference_game_files/game/in_game/common/goods",
        ROOT / "src/in_game/common/goods",
    ):
        for path in sorted(folder.glob("*.txt")):
            goods.update(re.findall(
                r"(?m)^(?:(?:REPLACE|INJECT|TRY_REPLACE|TRY_INJECT):)?(\w+)\s*=\s*\{",
                path.read_text(encoding="utf-8-sig"),
            ))
    if not goods:
        raise ValueError("No goods found; check the .eu5-base reference mount")
    return sorted(goods)


def effects(goods):
    lines = [
        "# Country scope; market/goods are typed scopes, amount/time are scalar script values.",
        "# Example: tv_sell_goods_with_temporary_supply_effect = { market = capital.market goods = goods:medicaments amount = 15 time = 6 }",
        "# Pays amount * price * time ONCE; offsets amount demand for time months. No inventory is added.",
        "# Internal tv_market_supply_* saved scopes are reserved for this synchronous call.",
        "tv_sell_goods_with_temporary_supply_effect = {",
        "\tif = {",
        "\t\tlimit = { exists = $market$ exists = $goods$ }",
        "\t\t# Capture inputs in the caller before changing scope or granting gold.",
        "\t\tsave_scope_value_as = { name = tv_market_supply_amount value = { value = $amount$ } }",
        "\t\tsave_scope_value_as = { name = tv_market_supply_months value = { value = $time$ } }",
        "\t\t$market$ = { save_scope_as = tv_market_supply_market }",
        "\t\t$goods$ = { save_scope_as = tv_market_supply_goods }",
        "\t\tif = {",
        "\t\t\tlimit = { scope:tv_market_supply_amount > 0 scope:tv_market_supply_months > 0 }",
        "\t\t\t# Dispatch before payment: an unregistered good must not grant free gold.",
    ]
    for index, good in enumerate(goods):
        branch = "if" if index == 0 else "else_if"
        lines += [
            f"\t\t\t{branch} = {{",
            f"\t\t\t\tlimit = {{ scope:tv_market_supply_goods = goods:{good} }}",
            "\t\t\t\ttv_sell_goods_with_temporary_supply_apply_effect = {",
            f"\t\t\t\t\tdemand = tv_market_supply_{good}",
            "\t\t\t\t}",
            "\t\t\t}",
        ]
    lines += [
        "\t\t}", "\t}", "}", "",
        "# Internal country-scope helper; only call through the guarded public effect.",
        "# Native sale tokens are adapted in localization; the value is the actual payout.",
        "tv_sell_goods_with_temporary_supply_apply_effect = {",
        "\tsave_scope_as = tv_market_supply_country",
        "\tcustom_description = {",
        f"\t\ttext = {DESCRIPTION}",
        "\t\tsubject = this",
        "\t\tobject = scope:tv_market_supply_market",
        # custom_description reads a single value target, not inline arithmetic.
        f"\t\tvalue = {PAYOUT_VALUE}",
        "\t\tadd_gold = {",
        f"\t\t\tvalue = {PAYOUT_VALUE}",
        "\t\t}",
        "\t\tscope:tv_market_supply_market = {",
        "\t\t\tadd_temporary_demand = {",
        "\t\t\t\ttype = demand:$demand$",
        "\t\t\t\tscale = { value = scope:tv_market_supply_amount }",
        # Duration fields accept a scalar; scale remains a script-value block.
        "\t\t\t\tmonths = scope:tv_market_supply_months",
        "\t\t\t}",
        "\t\t}",
        "\t}",
        "}",
    ]
    return "\n".join(lines) + "\n"


def sale_localizations(language):
    """Keep vanilla prose verbatim; bind native sale-only tokens explicitly.

custom_description only supplies subject/object/VALUE, not GOLD/AMOUNT/GOODS.
Do not alias the original keys without supplying those values, or call a native
sale just for its preview: its capital sell price can differ from our payout.
"""
    source = ROOT / f".eu5-base/reference_game_files/game/main_menu/localization/{language}/effects_l_{language}.yml"
    native = dict(re.findall(r'^\s*(\w+):(?:\d+)?\s*"(.*)"\s*$', source.read_text(encoding="utf-8-sig"), re.MULTILINE))
    replacements = {
        "$GOLD$": "$VALUE|2$",
        "$AMOUNT|+=2$": "[Multiply_CFixedPoint(SCOPE.GetValue('tv_market_supply_amount'), SCOPE.GetValue('tv_market_supply_months'))|+=2]",
        "$GOODS$": "[SCOPE.sGoods('tv_market_supply_goods').GetName]",
        "[COUNTRY.GetName]": "[SCOPE.sCountry('tv_market_supply_country').GetName]",
        "[TARGET_MARKET.GetName]": "[SCOPE.sMarket('tv_market_supply_market').GetName]",
        "[TARGET_MARKET.GetShortName]": "[SCOPE.sMarket('tv_market_supply_market').GetShortName]",
    }
    result = {}
    for perspective, key in SALE_LOCALIZATIONS.items():
        text = native[key]
        for original, binding in replacements.items():
            text = text.replace(original, binding)
        unresolved = set(re.findall(r"\$([^$]+)\$", text)) - {"VALUE|2"}
        if unresolved:
            raise ValueError(f"Unmapped vanilla sale tokens in {language}/{key}: {unresolved}")
        result[f"{DESCRIPTION}_{perspective}"] = text
    return result


def outputs():
    goods = goods_ids()
    demands = "\n\n".join(
        f"tv_market_supply_{good} = {{\n\t{good} = -1\n\thidden = yes\n\tcategory = special_demands\n}}"
        for good in goods
    ) + "\n"
    registry = [f"{DESCRIPTION} = {{", f"\tnone = {DESCRIPTION}_global"]
    registry += [f"\t{perspective} = {DESCRIPTION}_{perspective}" for perspective in SALE_LOCALIZATIONS]
    registry += ["}"]
    payout = (f'{PAYOUT_VALUE} = {{\n'
              '\tvalue = "scope:tv_market_supply_goods.price_in_market(scope:tv_market_supply_market)"\n'
              '\tmultiply = scope:tv_market_supply_amount\n'
              '\tmultiply = scope:tv_market_supply_months\n}\n')
    result = {EFFECT_PATH: effects(goods), DEMAND_PATH: demands, VALUES_PATH: payout,
              EFFECT_LOC_PATH: "\n".join(registry) + "\n"}
    for language in ("english", "simp_chinese"):
        lines = [f"l_{language}:"]
        lines += [f' {key}:0 "{text}"' for key, text in sale_localizations(language).items()]
        for good in goods:
            name = f"[ShowGoodsName('{good}')]"
            text = (f"临时{name}供应（需求抵消）" if language == "simp_chinese"
                    else f"Temporary {name} supply (demand offset)")
            lines.append(f' tv_market_supply_{good}:0 "{text}"')
        result[f"src/main_menu/localization/{language}/tv_market_supply_l_{language}.yml"] = "\n".join(lines) + "\n"
    return {path: HEADER + content for path, content in result.items()}


def main():
    for relative, content in outputs().items():
        target = ROOT / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8-sig", newline="\n")
        print(f"Wrote {relative}")


if __name__ == "__main__":
    main()
